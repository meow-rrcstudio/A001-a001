// 크레딧 규칙의 숫자들. 화면과 서버가 함께 봅니다.
//
// ⚠️ 이 파일에 "use client" 를 붙이면 안 됩니다.
//    붙이면 서버(app/api/**)가 이 값을 가져올 때 숫자가 아니라 클라이언트
//    참조 스텁을 받습니다. 그러면 DB 에 넣는 값이 망가지는데, 화면에는
//    아무 오류도 안 보이고 "가입했는데 크레딧이 0" 같은 모습으로만
//    나타나서 찾기가 아주 어렵습니다. (lib/layout.ts 에 같은 경고가 있고,
//    실제로 이 실수를 두 번 했습니다)

/**
 * 가입하면 얹어주는 첫 크레딧.
 *
 * 지금은 지인 스무 명 남짓과 하는 테스트 기간이라 넉넉히 열 장입니다.
 * 결제를 열기 전에 이 숫자를 다시 내려야 합니다 — 안 그러면 아무나
 * 가입해서 열 장씩 가져갑니다. (오픈 전 정리 목록에 함께 있습니다)
 *
 * ⚠️ 이 숫자는 "가입하는 순간"에만 쓰입니다. 이미 가입한 사람의 잔액은
 *    바뀌지 않습니다. 먼저 가입한 사람에게 더 주려면 크레딧 원장
 *    (credit_entries)에 직접 한 줄 넣어야 합니다.
 */
export const WELCOME_CREDITS = 1

/**
 * 가입 선물 판에 딸려오는 "이어서 묻기" 횟수.
 *
 * 산 판(FOLLOWUPS_PER_CREDIT)보다 적습니다. 선물은 맛보기고, 더 묻고
 * 싶으면 사는 것이 자연스럽습니다. 세 번이면 "한 번 되물어보고 한 번 더"
 * 까지는 되어서, 샨티와 말이 오간다는 느낌은 받습니다.
 *
 * ⚠️ 판을 만들 때 readings.followups_allowed 에 박히는 값이라, 나중에
 *    이 숫자를 바꿔도 이미 만들어진 판은 그대로입니다. 그게 맞습니다 —
 *    받을 때의 조건은 지켜져야 합니다.
 */
export const WELCOME_FOLLOWUPS = 3

/**
 * 크레딧 한 장에 딸려오는 "이어서 묻기" 횟수.
 *
 * 원가 때문에 두는 값이 아닙니다 — 한 판에 스무 번을 물어도 원가는
 * 백 원이 안 됩니다. 스크립트로 한 장에 수천 번 때리는 걸 막는
 * 방어선입니다. 보통은 서너 번 묻고 끝나서 이 숫자를 볼 일이 없습니다.
 *
 * 그래서 미터기처럼 보이면 안 됩니다. 남은 횟수는 끝이 가까울 때만
 * (FOLLOWUP_WARN_AT) 슬쩍 보여주고, 다 쓰면 막지 말고 "한 장 더 쓰고
 * 이어가기"를 권합니다. 물어보려던 걸 못 묻게 하는 게 제일 나쁩니다.
 */
export const FOLLOWUPS_PER_CREDIT = 10

/** 남은 횟수가 이보다 적어질 때부터 화면에 보여줍니다 */
export const FOLLOWUP_WARN_AT = 5

/**
 * 남은 횟수가 이보다 적어지면 "미리 한 장 더 쓰기"를 권합니다.
 *
 * FOLLOWUP_WARN_AT(5)과 나누는 이유: 다섯 번 남았을 때부터 결제를 권하면
 * 아직 한참 물어볼 수 있는 사람에게 미터기를 들이대는 셈입니다. 그래서
 * 다섯 번째부터는 남은 횟수만 조그맣게 보여주고, 정말 끝이 보이는
 * 두 번째부터만 권합니다.
 *
 * 다 쓴 뒤에 권하면 하려던 말이 끊깁니다 — 끊기기 전에 물어야 합니다.
 */
export const FOLLOWUP_NEARLY_DONE_AT = 2
