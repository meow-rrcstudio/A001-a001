//    붙이면 서버(app/api/**)가 이 값을 가져올 때 숫자가 아니라 클라이언트
//    참조 스텁을 받습니다. 그러면 DB 에 넣는 값이 망가지는데, 화면에는
//    아무 오류도 안 보이고 "가입했는데 크레딧이 0" 같은 모습으로만
//    나타나서 찾기가 아주 어렵습니다. (lib/layout.ts 에 같은 경고가 있고,
//    실제로 이 실수를 두 번 했습니다)

/**
 * 가입하면 얹어주는 첫 크레딧.
 *
 * 한 장입니다 — 한 판을 끝까지 보기에 딱 맞습니다. 맛보기로 충분하고,
 * 아무나 가입해서 여러 장 가져가지도 못합니다.
 *
 * ⚠️ 이 숫자는 "가입하는 순간"에만 쓰입니다. 이미 가입한 사람의 잔액은
 *    바뀌지 않습니다. 특정한 사람에게 더 주려면 크레딧 원장
 *    (credit_entries)에 직접 한 줄 넣습니다 — reason 은 'grant',
 *    idempotency_key 는 겹치지 않게 (없으면 실수로 두 번 들어갑니다).
 */
export const WELCOME_CREDITS = 1

/**
 * 별조각 유효기간 (개월).
 *
 * ┌─ 왜 1년인가 ──────────────────────────────────────────────────────
 * │ 법이 정한 최소 기간은 없습니다. 별조각은 우리 사이트에서만 쓰는
 * │ 자사 포인트라, 전자금융거래법의 선불전자지급수단 규제(가맹점이
 * │ 여럿인 경우)에 걸리지 않습니다. 기간은 회사가 정합니다.
 * │
 * │ 다만 상법 제64조의 상사채권 소멸시효가 5년이라, 유효기간이 지난
 * │ 뒤에도 5년 안에는 미사용분 환급을 요구할 수 있다고 보는 것이
 * │ 일반적입니다. 기간이 지났다고 무조건 거절하지는 마세요 —
 * │ 문서에 적힌 기간(약관 제5조)과 별개로 다툼의 여지가 있는 자리입니다.
 * └──────────────────────────────────────────────────────────────────
 *
 * ⚠️ 지금 이 값을 실제로 적용하는 코드는 없습니다. 별조각은 코드상
 *    만료되지 않습니다 — 문서에만 있는 규칙입니다. 회원에게 유리한 쪽으로
 *    어긋나 있는 셈이라 급하지 않습니다.
 *
 * ⚠️ 실제로 소멸시키기로 한다면 두 가지를 함께 만들어야 합니다.
 *      1) credit_entries 에 만료 차감을 넣는 일 (매일 도는 검사)
 *      2) 소멸 예정을 미리 알리는 일
 *    2번을 빼고 1번만 하면, 아무 말 없이 별조각이 사라집니다 — 통지가
 *    법적 의무는 아니지만 그 자체로 분쟁이 됩니다.
 *
 *    약관에는 "미리 알린다"고 적지 않았습니다. 알릴 수단(메일·알림톡)이
 *    아직 없어서입니다. 지키지 못할 말을 적어두느니 적지 않는 편이
 *    낫습니다. 알림을 만들게 되면 그때 약관에도 함께 넣으세요.
 */
export const PAID_CREDIT_VALID_MONTHS = 12

/** 무상 별조각 유효기간 (개월). 지금은 유상과 같습니다. */
export const FREE_CREDIT_VALID_MONTHS = 12

/**
 * 개월 수를 사람 말로 — "1년" · "18개월".
 *
 * ⚠️ 약관·환불정책이 이 함수를 씁니다. 기간을 바꾸면 문서가 저절로
 *    따라오도록 하기 위해서입니다. 문서에 "1년"을 손으로 적으면, 값을
 *    바꿨을 때 문서만 옛 기간으로 남습니다 — 환불정책에서 실제로
 *    그랬습니다(app/refund/page.tsx 의 예시 주석).
 */
export function validityLabel(months: number): string {
  return months % 12 === 0 ? `${months / 12}년` : `${months}개월`
}

/**
 * 가입 선물 판에 딸려오는 "이어서 묻기" 횟수.
 *
 * 산 판(FOLLOWUPS_PER_CREDIT)보다 적습니다. 선물은 맛보기고, 더 묻고
 * 싶으면 사는 것이 자연스럽습니다. 세 번이면 "한 번 되물어보고 한 번 더"
 * 까지는 되어서, 샨티와 말이 오간다는 느낌은 받습니다.
 *
 * ⚠️ 판을 만들 때 readings.followups_allowed 에 박히는 값이라, 나중에
 *    이 숫자를 바꿔도 이미 만들어진 판은 그대로입니다. 그게 맞습니다 —
 *    받을 때의 조건은 지켜져야 합니다.
 */
export const WELCOME_FOLLOWUPS = 3

/**
 * 크레딧 한 장에 딸려오는 "이어서 묻기" 횟수.
 *
 * 원가 때문에 두는 값이 아닙니다 — 한 판에 스무 번을 물어도 원가는
 * 백 원이 안 됩니다. 스크립트로 한 장에 수천 번 때리는 걸 막는
 * 방어선입니다. 보통은 서너 번 묻고 끝나서 이 숫자를 볼 일이 없습니다.
 *
 * 그래서 미터기처럼 보이면 안 됩니다. 남은 횟수는 끝이 가까울 때만
 * (FOLLOWUP_WARN_AT) 슬쩍 보여주고, 다 쓰면 막지 말고 "한 장 더 쓰고
 * 이어가기"를 권합니다. 물어보려던 걸 못 묻게 하는 게 제일 나쁩니다.
 */
export const FOLLOWUPS_PER_CREDIT = 10

/** 남은 횟수가 이보다 적어질 때부터 화면에 보여줍니다 */
export const FOLLOWUP_WARN_AT = 5

/**
 * 남은 횟수가 이보다 적어지면 "미리 한 장 더 쓰기"를 권합니다.
 *
 * FOLLOWUP_WARN_AT(5)과 나누는 이유: 다섯 번 남았을 때부터 결제를 권하면
 * 아직 한참 물어볼 수 있는 사람에게 미터기를 들이대는 셈입니다. 그래서
 * 다섯 번째부터는 남은 횟수만 조그맣게 보여주고, 정말 끝이 보이는
 * 두 번째부터만 권합니다.
 *
 * 다 쓴 뒤에 권하면 하려던 말이 끊깁니다 — 끊기기 전에 물어야 합니다.
 */
export const FOLLOWUP_NEARLY_DONE_AT = 2
