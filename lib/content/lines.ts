// 섞기 멘트 풀 — 질문마다 쓰지 않고 결(style)마다 모아 둡니다
//
// ┌─ 섞기만 풀인 까닭 ────────────────────────────────────────────────
// │ 「마음이 가는 곳을 따라 천천히 살펴보자냥」은 어느 질문에도 붙습니다.
// │ 질문 60개에 4개씩 240개를 쓸 까닭이 없고, 그만큼 쓰면 뒤로 갈수록
// │ 톤이 흐트러집니다 — 샨티는 질문마다 다른 캐릭터가 아니라 하나의
// │ 존재가 상황에 맞춰 말하는 것이라서요.
// │
// │ 확정 멘트(confirms)는 반대입니다. 「지금의 마음이라...」처럼 질문이
// │ 문장에 녹아 있어서 공용으로 만들면 무슨 질문이든 같은 틀이 됩니다 —
// │ 한동안 「무슨 질문이든 좋은 질문이구먼」이었던 까닭이 그것입니다.
// │ 그래서 확정 멘트는 질문마다 직접 씁니다.
// └──────────────────────────────────────────────────────────────────
//
// ⚠️ 결 이름은 자유 문자열이 아닙니다. 오타가 나면 풀을 못 찾고 그 질문만
//    조용히 빈 멘트가 되는데, 그건 그 질문을 눌러봐야 압니다.
//    타입으로 막고 scripts/check-content.mjs 가 한 번 더 셉니다.

