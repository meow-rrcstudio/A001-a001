// lib/content/ordinal.ts
// 「첫 번째 카드는 …」의 앞부분을 붙입니다.
//
// ┌─ 왜 문구에 안 박는가 ─────────────────────────────────────────────
// │ 자리를 하나 늘리거나 순서를 바꾸면 번호가 조용히 틀립니다. 콘텐츠에
// │ 「세 번째 카드는」이라고 적혀 있는데 실제로는 네 번째 자리에 놓이는
// │ 일이 생기고, 그건 그 스프레드를 실제로 뽑아봐야 압니다.
// │
// │ 콘텐츠에는 「지금 너의 마음을 비추는 카드다냥」만 적고, 번호는
// │ 놓이는 자리에서 붙입니다. 쓰는 사람도 그만큼 덜 칩니다.
// └──────────────────────────────────────────────────────────────────
const ORDINALS = [
  "첫 번째",
  "두 번째",
  "세 번째",
  "네 번째",
  "다섯 번째",
  "여섯 번째",
  "일곱 번째",
  "여덟 번째",
  "아홉 번째",
  "열 번째",
]

/** "첫 번째" — 열 번째까지는 우리말로, 그 뒤는 숫자로 */
export function ordinalOf(index: number): string {
  return ORDINALS[index] ?? `${index + 1}번째`
}

/**
 * 뽑기 직전에 건네는 한 마디.
 *
 * ⚠️ 마지막 장에는 「자 마지막이야」를 앞에 답니다. 예전 문구들이
 *    그렇게 맺고 있었고, 마지막이라는 신호가 있으면 뽑는 사람이
 *    한 번 더 마음을 담습니다.
 */
export function drawLine(short: string, index: number, total: number): string {
  // 한 장짜리에는 번호를 붙이지 않습니다 — 「첫 번째 카드는」이라고 하면
  // 두 번째가 있는 줄 알게 됩니다. 그 자리의 문구는 혼자 서게 씁니다.
  if (total === 1) return short

  const head = index === total - 1 ? "자 마지막이야. " : ""
  return `${head}${ordinalOf(index)} 카드는 ${short}`
}
