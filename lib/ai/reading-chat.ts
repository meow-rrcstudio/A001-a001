// lib/ai/reading-chat.ts
// 해석을 받은 뒤 이어지는 면담(추가 질문)의 형식 정의입니다.
//
// 지금까지 후속 답변은 lib/mock-reading.ts 의 고정 문구였습니다. 무엇을
// 물어도 같은 말이 돌아와서, 뽑은 카드와 아무 상관이 없었습니다.
//
// 여기서 정하는 것은 두 가지입니다.
//   1) 샨티의 답 (reply)
//   2) 카드를 더 봐야 할 때, 어떻게 더 볼지 (draw)
//
// ⚠️ 이 파일은 화면과 서버가 함께 봅니다. 서버 전용(api key 등) 코드를
//    여기에 넣지 마세요.

/** 추가로 뽑을 카드 한 자리 */
export interface ChatDrawPosition {
  label: string
  guide: string
}

/**
 * 카드를 더 봐야 할 때 샨티가 내놓는 요청.
 *
 * · mode="shanti" — 이 몸이 대신 뽑아준다. 사실 확인에 가까운 물음
 *   ("그래서 언제쯤이야?")일 때. 화면이 바로 뽑아 이어서 읽어줍니다.
 * · mode="user"   — 네가 직접 뽑아라. 묻는 이의 마음이 실려야 하는 물음
 *   ("그 사람한테 연락해도 될까?")일 때. 카드 고르기 화면으로 넘어갑니다.
 */
export interface ChatDrawRequest {
  mode: "shanti" | "user"
  /** 뽑기 직전에 건네는 말 */
  intro: string
  positions: ChatDrawPosition[]
}

export interface ChatReply {
  reply: string
  draw?: ChatDrawRequest | null
  /**
   * 이어서 물어볼 만한 것 0~3개.
   *
   * 답과 같은 요청 안에서 함께 받습니다 — 따로 부르면 요청 한 번을 더
   * 쓰는데, 하루 요청 수가 곧 한도입니다(lib/ai/gemini.ts 주석 참고).
   * 같은 한 번에서 더 많이 받아오는 쪽이 언제나 낫습니다.
   *
   * 화면에서는 입력창 위에 작은 알약으로 놓입니다. 무엇을 물어야 할지
   * 모를 때 대화가 끊기는 걸 막습니다 — 타로를 처음 보는 사람에게 특히
   * 그렇습니다.
   */
  suggestions?: string[]
  /**
   * 이 판에서 지금까지 오간 이야기를 한 덩어리로 접은 것.
   *
   * ⚠️ 화면은 이걸 쓰지 않습니다. 서버가 받아 판에 남겨두었다가, 다음
   *    물음에 함께 들려보냅니다.
   *
   * 면담에 실어보내는 대화는 최근 열두 마디까지입니다(라우트 참고).
   * 그보다 앞의 말은 그냥 사라져서, 대화 초반에 묻는 이가 털어놓은 사정이
   * 열세 마디째부터 없던 일이 됐습니다. 밀려나기 전에 접어두는 것이
   * 이 값입니다.
   *
   * 답과 같은 요청 안에서 함께 받습니다 — suggestions 와 같은 이유입니다.
   * 요약하자고 요청을 한 번 더 쓰면 하루 스무 번이 열 번이 됩니다.
   */
  digest?: string | null
  /**
   * 이번 마디에서 새로 알게 된, 이 사람에 대한 사실 0~2개.
   *
   * ⚠️ 화면은 이걸 쓰지 않습니다. 서버가 받아 user_memories 에 쌓았다가,
   *    다음에 이 사람이 올 때 — 다른 판이어도 — 함께 들려보냅니다.
   *
   * digest 가 "이 판에서 있었던 일"이라면 이쪽은 "이 사람에 대해 알게 된
   * 것"입니다. 판이 끝나도 남습니다.
   *
   * 대개 빈 배열입니다. 억지로 채우면 추측이 사실로 굳어서, 다음 대화에서
   * 샨티가 틀린 것을 알고 있는 척하게 됩니다.
   */
  memo?: ChatMemo[] | null
}

/** 한 번에 제안할 다음 물음의 최대 개수 */
export const CHAT_SUGGESTION_MAX = 3

/** 한 번에 더 뽑을 수 있는 최대 장수 — 면담이 끝없이 늘어지지 않도록 */
export const CHAT_DRAW_MAX = 3

/**
 * 이야기를 접기 시작하는 마디 수.
 *
 * 이보다 짧으면 오간 말이 통째로 프롬프트에 들어가 있어서 접어둘 것이
 * 없습니다. 라우트가 잘라내는 열두 마디보다 넉넉히 앞에 두어, 밀려나기
 * 전에 접힐 시간을 둡니다.
 */
export const CHAT_DIGEST_MIN_TURNS = 4

/** 접어둔 이야기의 길이 상한 — 이게 길어지면 대화를 밀어냅니다 */
export const CHAT_DIGEST_MAX_CHARS = 600

/**
 * 이 사람에 대해 알게 된 것 — 갈래.
 *
 *   situation 지금 놓인 처지   (이직을 준비하고 있다)
 *   person    주변 사람        (3년 만난 사람이 있다)
 *   trait     성향             (결정을 미루는 편이다)
 *   care      대하는 법        (조언보다 들어주기를 원한다)
 *
 * care 가 이 중 가장 중요합니다. 다른 셋은 "무엇을 아는가"지만 care 는
 * "어떻게 말할 것인가"라서, 상담의 결이 사람마다 갈리는 자리입니다.
 */
export const CHAT_MEMO_KINDS = ["situation", "person", "trait", "care"] as const
export type ChatMemoKind = (typeof CHAT_MEMO_KINDS)[number]

export interface ChatMemo {
  kind: ChatMemoKind
  fact: string
}

