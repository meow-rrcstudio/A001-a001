// lib/login-href.ts
// "로그인하기"를 눌렀을 때 돌아올 곳을 붙여줍니다.
//
// ┌─ 왜 필요한가 ─────────────────────────────────────────────────────
// │ 로그인 화면은 next= 로 "마치고 어디로 갈지"를 받습니다. 그런데 그걸
// │ 붙이지 않은 버튼이 여럿이었습니다. 설정에서 로그인하면 설정으로
// │ 돌아와야 하는데 기록 목록에 떨어지고, 홈에서 로그인해도 기록 목록에
// │ 떨어졌습니다 — 로그인은 "하던 일을 이어가려고" 하는 것인데, 하던
// │ 일과 상관없는 화면에 내려놓으면 무엇을 하려 했는지 잊게 됩니다.
// │
// │ 버튼마다 주소를 손으로 적으면 화면을 옮길 때 그 주소만 옛 것으로
// │ 남습니다. 지금 서 있는 자리를 물어보는 편이 어긋나지 않습니다.
// └──────────────────────────────────────────────────────────────────
"use client"

import { usePathname } from "next/navigation"

/**
 * 지금 화면으로 돌아오는 로그인 주소.
 *
 * @param to 돌아올 곳을 직접 정하고 싶을 때 (예: 방금 본 타로점).
 *           비우면 지금 서 있는 화면으로 돌아옵니다.
 *
 * ⚠️ 로그인이 필요해서 내용을 감춘 화면에서 쓸 때는 그 화면 그대로가
 *    맞습니다 — 로그인하고 나면 감춰졌던 내용이 바로 보입니다.
 */
export function useLoginHref(to?: string): string {
  const pathname = usePathname()
  const next = to ?? pathname
  // 홈으로 돌아가는 것은 기본값이라 꼬리표를 붙이지 않습니다 (주소가 깔끔해집니다)
  if (!next || next === "/") return "/login"
  return `/login?next=${encodeURIComponent(next)}`
}
