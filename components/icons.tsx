// ┌─ 왜 SVG 파일이 아니라 컴포넌트인가 ───────────────────────────────
// │ 받은 원본에는 색이 박혀 있었습니다 (#33363F · black). 파일 그대로
// │ <img> 로 쓰면 그 색을 바깥에서 바꿀 수 없습니다 — 활성 상태나 검정
// │ 바탕에 놓을 때 대응할 길이 없어집니다.
// │
// │ 그래서 안으로 들여오면서 색을 currentColor 로 바꿨습니다. 이제
// │ 글자색을 따라갑니다 — text-foreground 를 주면 그 색이 됩니다.
// │ 파일도 여기 한 곳뿐이라 원본과 사본이 어긋날 일이 없습니다.
// └──────────────────────────────────────────────────────────────────
//
// ┌─ 아이콘을 더할 때 ────────────────────────────────────────────────
// │ 1) 피그마에서 20×20 으로 내보냅니다 (선 굵기 1.667 로 맞춰야 나머지와
// │    같은 무게로 보입니다)
// │ 2) stroke="..." · fill="..." 의 색값을 전부 currentColor 로 바꿉니다
// │ 3) <clipPath> 는 지웁니다 — 받은 원본에 들어 있지만 실제로 자르는
// │    것이 없고, 같은 아이콘이 한 화면에 두 번 나오면 id 가 겹칩니다
// │ 4) 아래 IconProps 를 받아 <Svg> 로 감쌉니다
// │ 5) 파일 맨 아래 ICON_SET 에 한 줄 더합니다 — 디자인시스템
// │    (app/design-1859)의 아이콘 절이 그 목록을 그대로 그리므로,
// │    거기까지 손댈 필요가 없습니다
// └──────────────────────────────────────────────────────────────────
import type { SVGProps } from "react"

export type IconProps = SVGProps<SVGSVGElement>

/**
 * 아이콘 공통 껍데기.
 *
 * 크기를 width/height 로 박지 않고 글자 크기(1em)에 맞춥니다. 옆에 놓인
 * 글과 자연스럽게 어울리고, 부르는 쪽에서 h-5 w-5 같은 것으로 덮어쓸 수도
 * 있습니다.
 */
function Svg({ children, ...props }: IconProps & { children: React.ReactNode }) {
  return (
    <svg
      viewBox="0 0 20 20"
      fill="none"
      xmlns="http://www.w3.org/2000/svg"
      width="1em"
      height="1em"
      // 뜻은 옆의 글자가 전합니다. 읽어주면 같은 말이 두 번 들립니다.
      aria-hidden="true"
      focusable="false"
      {...props}
    >
      {children}
    </svg>
  )
}

