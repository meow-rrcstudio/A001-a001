-- supabase/migrations/006-toss-account.sql
-- 앱인토스 미니앱으로 들어온 사람을 알아보기 위한 자리.
--
-- ┌─ 왜 필요한가 ─────────────────────────────────────────────────────
-- │ 미니앱에서는 카카오·구글·이메일을 쓸 수 없습니다(정책). 토스 로그인만
-- │ 됩니다. 토스는 사람을 `userKey` 라는 값으로 알려주는데, 다음에 다시
-- │ 들어왔을 때 "아까 그 사람"인 줄 알아보려면 그 값을 붙들어 둬야 합니다.
-- └──────────────────────────────────────────────────────────────────
--
-- ⚠️ 웹 계정과 잇지 않습니다 (docs/apps-in-toss.md §3 의 결정).
--    토스로 들어온 사람은 자기 계정을 따로 갖습니다. 잘못 이으면 남의
--    별조각이 보이는 사고가 나는데, 그걸 안전하게 하려면 본인 확인 화면이
--    따로 있어야 합니다. 초기 미니앱 사용자는 웹 사용자와 거의 겹치지
--    않으니, 겹치기 시작하면 그때 이어도 늦지 않습니다.
--
--    다만 이 칸을 지금 두는 까닭은, 나중에 이을 때 "누가 누구인지"를
--    되짚을 수 있어야 하기 때문입니다. 지금 안 남기면 나중에 못 잇습니다.
--
-- ⚠️ 가입 선물이 사람당 한 번이 아니라 **계정당 한 번**이 됩니다.
--    웹에 계정이 있는 사람이 미니앱으로 들어오면 선물을 한 번 더 받습니다.
--    계정을 따로 두기로 한 결과라 지금은 그대로 둡니다 — 나중에 이을 때
--    함께 정리하세요.

alter table public.profiles
  add column if not exists toss_user_key text;

-- ⚠️ 반드시 unique 여야 합니다. 없으면 같은 사람이 들어올 때마다 계정이
--    새로 생기고, 어제 산 별조각이 오늘 사라진 것처럼 보입니다.
--    (부분 인덱스인 까닭: 웹 계정은 이 값이 없어서 전부 null 입니다.
--     null 이 여럿인 것은 막으면 안 됩니다)
create unique index if not exists profiles_toss_user_key_key
  on public.profiles (toss_user_key)
  where toss_user_key is not null;

comment on column public.profiles.toss_user_key is
  '앱인토스 로그인이 알려주는 사용자 식별자. 웹 계정에는 없습니다(null).';
